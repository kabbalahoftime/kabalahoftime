"""Set the Daily Companion as a book.

    python3 -I tools/build_companion_book.py companion-days.json docs/daily-companion.md
    python3 tools/make_book_pdf.py docs/daily-companion.md daily-companion.pdf

The companion is 364 written entries, one to each day — one KoT Book for one
week, each day, filed the way Binah files them. On the page a reader meets one
of them at a time. On paper they are a book, and this is the manuscript for it.

WHY THIS IS GENERATED, WHEN EVERY OTHER MANUSCRIPT IN docs/ IS WRITTEN

Because the companion already has a manuscript, and it is not this file. The
entries are written in docs/companion-summaries.md, built into
companion-days.json by tools/build_companion_days.py, and checked against
their own blog posts by tools/check_companion_summaries.py. A second
hand-written copy for the printer would be a second place to edit and a second
thing to fall out of date, and the first time someone fixed a sentence in one
and not the other the book and the app would quietly disagree.

So this reads the built JSON — the same file the app fetches — and the chain
runs one way:

    docs/companion-summaries.md  →  companion-days.json  →  docs/daily-companion.md  →  the PDF

Edit the summaries. Rebuild the JSON. Rebuild this. Never edit this file or
the PDF, the way you never edit companion-days.json.

WEEKS OPEN PAGES, DAYS DO NOT

make_book_pdf.py opens a page at every `##`, and this is the thing that has
kept the companion off paper until now: 364 entries under 364 `##` headings
would be 364 pages with one short reading on each, most of them two-thirds
white. The same objection is written against a-year-inside-the-day.pdf in
CLAUDE.md.

The fix is that the companion is not actually 364 of anything — it is 52
weeks of 7. So `##` takes the week, which is 52 page openings, and `###`
takes the day, which is a chapter heading: centred, with air above it, held
to the paragraph beneath so a day can never open at the foot of a page. Seven
readings to a week and the week reads as the chapter it is.
"""
import json, pathlib, re, sys

# Cormorant Garamond has no emoji and neither has the FreeSerif the setter
# falls back to, so a book emoji would print as a blank box — the same way
# 6,900 Hebrew characters once did. The movement titles carry one each; it
# comes off here rather than being noticed in the PDF.
EMOJI = re.compile('[\U0001F000-\U0001FAFF←-⇿⌀-➿'
                   '⬀-⯿︎️]')

# Roman for the weeks, which is what a part heading wants. Fifty-two of them.
ONES = ['', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX']
TENS = ['', 'X', 'XX', 'XXX', 'XL', 'L']


def roman(n):
    return TENS[n // 10] + ONES[n % 10]


def clean(s):
    """A heading with no emoji in it, and no separator left hanging."""
    return EMOJI.sub('', str(s or '')).strip().strip('·').strip()


def main(src_path, out_path):
    data = json.loads(pathlib.Path(src_path).read_text(encoding='utf-8'))
    days = data['days']

    lines = [
        '# A Daily Companion',
        '',
        '### a reading for each of the 364 days — '
        'one KoT Book for one week, each day',
        '',
        # Everything before the first `##` is dropped by the setter, which is
        # why the note can stand here and nowhere else: after the subtitle,
        # so it does not steal the slot the subtitle is read from, and before
        # the first week, so it is never printed.
        '<!-- Generated by tools/build_companion_book.py from '
        'companion-days.json. Edit docs/companion-summaries.md instead. -->',
        '',
    ]

    seen_week = None
    for key in sorted(days, key=int):
        e = days[key]
        n, week = int(key), e['week']
        if week != seen_week:
            seen_week = week
            first = (week - 1) * 7 + 1
            lines += [
                f'## Week {roman(week)} | {clean(e.get("weekTitle"))} | '
                f'Days {first}–{first + 6}',
                '',
            ]
        lines += [f'### Day {n} · {clean(e.get("movementTitle"))} | '
                  f'{clean(e.get("title"))}', '']
        body = e['body']
        for para in (body if isinstance(body, list) else [str(body or '')]):
            # One line to a paragraph. A block that still has a line break in
            # it when it reaches the setter is verse, and every block under
            # the same heading goes with it — so a stray newline here would
            # set a whole day's reading ragged right and indented.
            lines += [' '.join(str(para).split()), '']
        if e.get('source'):
            label = clean(e.get('sourceLabel')) or 'the whole entry'
            lines += [f'*[{label}]({e["source"]})*', '']

    pathlib.Path(out_path).write_text('\n'.join(lines), encoding='utf-8')

    words = sum(len(' '.join(str(p).split()).split())
                for e in days.values() for p in e['body'])
    weeks = len({e['week'] for e in days.values()})
    print(f'{len(days)} entries over {weeks} weeks, {words:,} words of body')
    print(f'wrote {out_path}')
    return 0


if __name__ == '__main__':
    sys.exit(main(*sys.argv[1:3]))
