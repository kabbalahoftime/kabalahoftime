// Run with: node fetch-hayomyom.mjs
// Fetches all HaYom Yom entries from Sefaria and writes the HAYOM_YOM JS object.
// Output is written to hayomyom-data.js — paste its contents into index.html.

import { writeFileSync } from 'fs';

// Hebrew month number → Sefaria name, matching the app's hMonth convention:
// 7=Tishrei 8=Cheshvan 9=Kislev 10=Tevet 11=Shevat 12=Adar 13=Adar II
// 1=Nisan 2=Iyar 3=Sivan 4=Tammuz 5=Av 6=Elul
const MONTHS = [
  { num: 7,  name: 'Tishrei' },
  { num: 8,  name: 'Cheshvan' },
  { num: 9,  name: 'Kislev' },
  { num: 10, name: 'Tevet' },
  { num: 11, name: 'Shevat' },
  { num: 12, name: 'Adar' },
  { num: 13, name: 'Adar II' },
  { num: 1,  name: 'Nisan' },
  { num: 2,  name: 'Iyar' },
  { num: 3,  name: 'Sivan' },
  { num: 4,  name: 'Tammuz' },
  { num: 5,  name: 'Av' },
  { num: 6,  name: 'Elul' },
];

function stripHtml(str) {
  return str.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&lt;/g, '<')
            .replace(/&gt;/g, '>').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
}

async function fetchMonth(monthName) {
  const url = `https://www.sefaria.org/api/texts/HaYom_Yom.${encodeURIComponent(monthName)}?context=0&pad=0`;
  const res = await fetch(url, { headers: { 'User-Agent': 'KabbalahOfTime/1.0' } });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${monthName}`);
  const data = await res.json();
  // text is an array where index 0 = day 1
  const texts = Array.isArray(data.text) ? data.text : [];
  return texts.map(t => {
    if (!t) return '';
    if (Array.isArray(t)) t = t.join(' ');  // some entries are arrays of paragraphs
    return stripHtml(String(t));
  });
}

const entries = {};
let total = 0;

for (const { num, name } of MONTHS) {
  process.stdout.write(`Fetching ${name}...`);
  try {
    const days = await fetchMonth(name);
    days.forEach((text, i) => {
      if (text) {
        entries[`${num}-${i + 1}`] = text;
        total++;
      }
    });
    console.log(` ${days.filter(Boolean).length} entries`);
  } catch (e) {
    console.log(` ERROR: ${e.message}`);
  }
  // Be polite to Sefaria's servers
  await new Promise(r => setTimeout(r, 300));
}

// Build JS output
const lines = ['  // HaYom Yom — auto-generated by fetch-hayomyom.mjs'];
lines.push('  // Keys: "{hMonth}-{hDay}"  (month numbers match app convention)');
lines.push('  const HAYOM_YOM = {');
for (const [key, text] of Object.entries(entries)) {
  const escaped = text.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  lines.push(`    "${key}": "${escaped}",`);
}
lines.push('  };');

const output = lines.join('\n');
writeFileSync('hayomyom-data.js', output, 'utf8');
console.log(`\nDone — ${total} entries written to hayomyom-data.js`);
console.log('Paste the contents of hayomyom-data.js into index.html,');
console.log('replacing the line:  const HAYOM_YOM = {};');
